// Loop through numbers from 1 to 20
for (let i = 1; i <= 20; i++) {
    // If the remainder is 0 when divided by 2, it is even
    if (i % 2 === 0) {
        console.log(`${i} is an Even number`);
    } 
    // Otherwise, the number is odd
    else {
        console.log(`${i} is an Odd number`);
    }
}
